-- 1. Rooms Table (Updated with INR pricing)
CREATE TABLE rooms (
    room_number VARCHAR2(10) PRIMARY KEY,
    room_type VARCHAR2(50) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    is_available NUMBER(1) DEFAULT 1 -- 1 for Available, 0 for Booked
);

