-- 2. Reservations Header Table (Stores totals for the whole booking)
CREATE TABLE reservations (
    reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    contact_number VARCHAR2(15) NOT NULL,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    subtotal NUMBER(10, 2) NOT NULL,
    total_rent NUMBER(10, 2) NOT NULL
);

-- 3. Reserved Rooms Detail Table (Allows multiple rooms per reservation)
CREATE TABLE reserved_rooms (
    reservation_id NUMBER NOT NULL,
    room_number VARCHAR2(10) NOT NULL,
    PRIMARY KEY (reservation_id, room_number),
    FOREIGN KEY (reservation_id) REFERENCES reservations(reservation_id) ON DELETE CASCADE,
    FOREIGN KEY (room_number) REFERENCES rooms(room_number)
);

COMMIT;

