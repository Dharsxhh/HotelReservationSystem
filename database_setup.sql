-- Create the Rooms table
CREATE TABLE rooms (
    room_id NUMBER PRIMARY KEY,
    room_type VARCHAR2(50) NOT NULL,
    price NUMBER(10, 2) NOT NULL,
    is_available CHAR(1) DEFAULT 'Y' CHECK (is_available IN ('Y', 'N'))
);

-- Create the Reservations table
CREATE TABLE reservations (
    reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_name VARCHAR2(100) NOT NULL,
    guest_phone VARCHAR2(20) NOT NULL,
    room_id NUMBER,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    CONSTRAINT fk_room FOREIGN KEY (room_id) REFERENCES rooms(room_id)
);

